def _cache_bytes(t):
    if t is None:
        return 0
    if isinstance(t, (tuple, list)):
        return sum((_cache_bytes(_v) for _v in t))
    try:
        nbytes = int(t.numel()) * int(t.element_size())
        # Views can share storage: charge min(logical size, storage size) so a
        # stride-0 expand and a sliced view of a larger buffer are not
        # over-counted.
        try:
            nbytes = min(nbytes, int(t.untyped_storage().nbytes()))
        except Exception:
            pass
        return nbytes
    except Exception:
        return 0

def _mask_cache_total(cache):
    return sum((_cache_bytes(v) for v in cache.values()))

def _cache_attachment_bytes(t):
    """Host bytes attached to a cached tensor (currently `_pool_cpu`).

    `blocks_fixed` caches one block-id tensor per sequence length and attaches
    the segmenter's host counts row to it.  For the block_size=1 arm that row
    is the same size as the int64 tensor itself, so leaving it out of the
    budget would let `_IDX_CACHE` retain roughly twice the advertised bytes.
    """
    if t is None:
        return 0
    if isinstance(t, (tuple, list)):
        return sum((_cache_attachment_bytes(_v) for _v in t))
    cpu = getattr(t, '_pool_cpu', None)
    if cpu is None:
        return 0
    try:
        counts = cpu[0]
    except (TypeError, IndexError, KeyError):
        return 0
    if isinstance(counts, np.ndarray):
        return int(counts.nbytes)
    try:
        # A Python int list stores one machine-word pointer per block; the
        # integer objects themselves are bounded by the small-table contract.
        return 8 * len(counts)
    except TypeError:
        return 0

def _idx_cache_total(cache):
    return sum((_cache_bytes(v) + _cache_attachment_bytes(v)
                + 128 * len(k) for k, v in cache.items()))

def _is_pinned_key(key):
    return key in _PINNED_KEYS
_PINNED_KEYS = set()

_CACHE_STATS = {}


def _cache_item_bytes(key, value, total_of):
    n = _cache_bytes(value)
    if total_of is _idx_cache_total:
        n += _cache_attachment_bytes(value) + 128 * len(key)
    return n


def _cache_stat(cache):
    st = _CACHE_STATS.get(id(cache))
    if st is None or st.get('obj') is not cache:
        st = {'obj': cache, 'total': 0}
        _CACHE_STATS[id(cache)] = st
    return st


def _evictable_limit(cache, limit, total_of):
    pinned = sum((_cache_bytes(cache[k]) for k in _PINNED_KEYS if k in cache))
    return limit - pinned if pinned < limit else 0


def _cache_touch(cache, key):
    """Mark a cache entry as most-recently used (LRU, not FIFO)."""
    try:
        val = cache.pop(key)
    except KeyError:
        return None
    cache[key] = val
    return val


def _cache_get(cache, key):
    """LRU read: return the entry and move it to the recent end."""
    hit = _cache_touch(cache, key)
    return hit


def _cache_put(cache, key, tensor, limit, total_of):
    st = _cache_stat(cache)
    if key in cache:
        st['total'] -= _cache_item_bytes(key, cache[key], total_of)
        # Re-inserting an existing key refreshes its recency as well.
        try:
            cache.pop(key)
        except KeyError:
            pass
    cache[key] = tensor
    st['total'] += _cache_item_bytes(key, tensor, total_of)
    total = st['total']
    if total > limit:
        # Oldest-first eviction without copying the whole key list on every
        # insert (the cache can hold thousands of small index tables).  A
        # pinned entry is rotated to the recent end so the next iteration can
        # reach an evictable one; if a full rotation finds none, the loop
        # stops exactly like the former single-pass form.
        while total > limit and cache:
            _seen = 0
            _n = len(cache)
            while _seen < _n and total > limit:
                _k = next(iter(cache))
                if _is_pinned_key(_k):
                    cache[_k] = cache.pop(_k)
                    _seen += 1
                    continue
                st['total'] -= _cache_item_bytes(_k, cache.pop(_k), total_of)
                total = st['total']
                break
            else:
                break
    return total
