    key = (_dev_str(device), 'cwf', int(T), int(window), str(dtype))
    if window <= 0 or window >= T:
        base = causal_mask(T, device)
        if base.dtype == dtype:
            return base
        m = _cache_get(_MASK_CACHE, key)
