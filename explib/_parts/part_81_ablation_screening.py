# ---- 预算受限的消融筛选：分数因子设计、别名结构与主效应推断 --------------
#
# §136/§143 已经把「完整 2^k 子集晶格」作为组件归因的识别条件：只有每个
# 子集都被测量，Shapley/交互才可识别；星形留一设计不是晶格。这个条件在
# k=5/6 时是 32/64 个臂 × n seeds，通常超出一次实验的预算。现有
# `ablation_lattice_design` 会把缺口定价并明确拒绝把星形设计叫作归因，但
# 它没有给出**预算内的正向替代设计**。
#
# 本片段补上经典的 2^(k-p) 分数因子筛选设计：
#
#   * 由声明式 defining relations（乘积恒等于 +1 的字）生成一个正则分数；
#   * 显式报告 resolution、每个目标项的别名类（coset）与高阶混杂；
#   * 只拟合「每个别名类一个代表 + 全部主效应」的模型；
#   * 逐种子 OLS 得到效应，再走仓库既有的 exact sign-flip / max-T / Holm；
#   * 把 design、inputs.cells、模型项、别名表和推断结果做成可重放 artifact。
#
# 这不是完整晶格的替代品：分数设计里主效应可能与 2FI 混杂（resolution
# III），2FI 之间也可能彼此混杂（resolution IV）。因此结果必须同时携带
# `aliased_with` / `screening_assumption`，不能把混杂项分别写成两个独立
# 效应。只有 resolution V 及以上、且所有目标项都在自己的别名类里单独
# 出现时，才许可「主效应与 2FI 可分开」的措辞。
#
# Sign convention: 与 §136 一致，输入是 PPL，拟合在 log PPL 上；effect 定义为
# active level 减 inactive level，负值 = 组件降低 PPL（有益）。主效应尺度为
# 2*coef，二阶交互尺度为 4*coef，这样与仓库既有的
# `(11 - 10) - (01 - 00)` 交互定义同一单位。
#
# 本片段不读 truth/test split、不重算 PPL、不修改任何冻结 p/Holm/verdict，
# 也不把 screening 结果升级成完整晶格上的 Shapley 归因。

