def _asc_repr(value, *, limit=160):
    try:
        text = repr(value)
    except Exception:
        return f'<unrepresentable {type(value).__name__}>'
    return text if len(text) <= limit else text[:limit - 3] + '...'


def _asc_finite(value, *, where, positive=False):
    if isinstance(value, (bool, np.bool_)):
        raise ValueError(
            f'{where}: expected a finite number, got {_asc_repr(value)}')
    if isinstance(value, (str, bytes, bytearray)) or value is None:
        raise ValueError(
            f'{where}: expected a finite number, got {_asc_repr(value)}')
    try:
        out = float(value)
    except (TypeError, ValueError, OverflowError):
        raise ValueError(
            f'{where}: expected a finite number, got {_asc_repr(value)}'
        ) from None
    if not _asc_math.isfinite(out):
        raise ValueError(
            f'{where}: expected a finite number, got {_asc_repr(value)}')
    if positive and out <= 0.0:
        raise ValueError(
            f'{where}: expected a positive PPL, got {_asc_repr(value)}')
    return out


def _asc_int(value, *, where, minimum=None, maximum=None):
    if isinstance(value, (bool, np.bool_)):
        raise ValueError(
            f'{where}: expected an integer, got {_asc_repr(value)}')
    try:
        out = int(value)
    except (TypeError, ValueError, OverflowError):
        raise ValueError(
            f'{where}: expected an integer, got {_asc_repr(value)}') from None
    try:
        if value != out:
            raise ValueError(
                f'{where}: expected an integer, got {_asc_repr(value)}')
    except (TypeError, ValueError, OverflowError):
        raise ValueError(
            f'{where}: expected an integer, got {_asc_repr(value)}') from None
    if minimum is not None and out < minimum:
        raise ValueError(
            f'{where}: expected an integer >= {minimum}, got '
            f'{_asc_repr(value)}')
    if maximum is not None and out > maximum:
        raise ValueError(
            f'{where}: expected an integer <= {maximum}, got '
            f'{_asc_repr(value)}')
    try:
        # A count that cannot be stringified cannot be written as JSON.
        str(out)
    except (ValueError, MemoryError):
        raise ValueError(
            f'{where}: integer is too large to represent as JSON') from None
    return out


def _asc_components(value):
    """Canonical sorted component names; separators are reserved."""
    if value is None or isinstance(value, (str, bytes, bytearray)):
        raise ValueError('components must be an iterable of names')
    try:
        raw = list(value)
    except TypeError:
        raise ValueError(
            f'components must be an iterable, got {type(value).__name__}'
        ) from None
    names = []
    for i, item in enumerate(raw):
        if not isinstance(item, str) or not item.strip():
            raise ValueError(
                f'components[{i}]: names must be non-empty strings, got '
                f'{_asc_repr(item)}')
        name = item.strip()
        if any(ch in name for ch in '+,|,'):
            raise ValueError(
                f'components[{i}]: name {name!r} contains a separator')
        if name in names:
            raise ValueError(f'components[{i}]: duplicate name {name!r}')
        names.append(name)
    if len(names) < 2:
        raise ValueError(
            f'a screening design needs at least 2 components, got {len(names)}')
    if len(names) > ASC_MAX_COMPONENTS:
        raise ValueError(
            f'{len(names)} components exceed ASC_MAX_COMPONENTS='
            f'{ASC_MAX_COMPONENTS}; use a full lattice or a smaller scope')
    return sorted(names)


def _asc_relation_word(value, components, *, where):
    if isinstance(value, str):
        parts = [p.strip() for p in value.split('+') if p.strip()]
    elif isinstance(value, (list, tuple, set, frozenset)):
        parts = list(value)
    else:
        raise ValueError(
            f'{where}: a defining relation must be a list of component names '
            f'or a "+"-joined string, got {type(value).__name__}')
    if not parts:
        raise ValueError(f'{where}: empty defining relation')
    names = []
    for i, item in enumerate(parts):
        if not isinstance(item, str) or not item.strip():
            raise ValueError(
                f'{where}[{i}]: relation members must be non-empty strings, '
                f'got {_asc_repr(item)}')
        name = item.strip()
        if name not in components:
            raise ValueError(
                f'{where}[{i}]: unknown component {name!r}; declared '
                f'components are {components}')
        if name in names:
            raise ValueError(
                f'{where}: relation repeats component {name!r}')
        names.append(name)
    if len(names) < 2:
        raise ValueError(
            f'{where}: a defining relation must contain at least 2 components')
    return frozenset(names)


def _asc_relations(components, relations):
    """Canonical independent defining relations (any word length >= 2)."""
    if relations is None:
        relations = []
    if isinstance(relations, (str, bytes, bytearray)):
        raise ValueError('defining_relations must be a list of relations')
    try:
        raw = list(relations)
    except TypeError:
        raise ValueError('defining_relations must be a list of relations'
                         ) from None
    if len(raw) > ASC_MAX_RELATIONS:
        raise ValueError(
            f'{len(raw)} defining relations exceed ASC_MAX_RELATIONS='
            f'{ASC_MAX_RELATIONS}')
    index = {name: i for i, name in enumerate(components)}
    words = []
    for i, relation in enumerate(raw):
        word = _asc_relation_word(relation, components, where=(
            f'defining_relations[{i}]'))
        mask = 0
        for name in word:
            mask |= 1 << index[name]
        if mask in words:
            raise ValueError(
                f'defining_relations[{i}]: duplicate relation {sorted(word)!r}')
        words.append(mask)
    if len(words) >= len(components):
        raise ValueError(
            f'{len(words)} independent relations leave no cells for '
            f'{len(components)} components')
    # Independence over GF(2): each generator must add one rank.  A dependent
    # generator would make the declared p larger than the actual fraction.
    basis = {}
    for i, mask in enumerate(words):
        rest = mask
        while rest:
            bit = rest.bit_length() - 1
            if bit in basis:
                rest ^= basis[bit]
            else:
                basis[bit] = rest
                break
        if rest == 0:
            raise ValueError(
                f'defining_relations[{i}] is linearly dependent on the '
                'preceding relations; declare only an independent generating '
                'set')
    canonical = []
    for mask in words:
        canonical.append(sorted((components[i] for i in range(len(components))
                                 if mask & (1 << i))))
    canonical.sort(key=lambda word: (len(word), tuple(word)))
    return canonical


def _asc_mask(word, components):
    index = {name: i for i, name in enumerate(components)}
    return sum(1 << index[name] for name in word)


def _asc_span(relations, components):
    masks = [_asc_mask(word, components) for word in relations]
    span = [0]
    for mask in masks:
        span = span + [value ^ mask for value in span]
    return sorted(span)


def _asc_popcount(mask):
    return int(mask).bit_count()


def _asc_term_name(mask, components):
    return '+'.join(components[i] for i in range(len(components))
                    if mask & (1 << i))


def _asc_cell_label(mask, components):
    name = _asc_term_name(mask, components)
    return name if name else '<empty>'


def _asc_all_words(k):
    return [mask for mask in range(1, 1 << k)
            if mask != 0]


def _asc_roman(value):
    table = {3: 'III', 4: 'IV', 5: 'V', 6: 'VI', 7: 'VII', 8: 'VIII',
             9: 'IX'}
    return table.get(value, str(value))


def fractional_factorial_design(components, *, defining_relations=None,
                                max_order=2, n_seeds=5, alpha=0.05):
    """Build and audit one regular ``2^(k-p)`` ablation screening design.

    ``defining_relations`` is a list of words whose product is identically +1
    on the fraction (for example ``[['A', 'B', 'C', 'D']]`` for a 2^(4-1)
    resolution IV design).  An empty list is a full factorial.  The function
    returns the measured cells, the alias class of every term up to
    ``max_order``, the model terms that can be fitted together, the resolution,
    and the exact budget saving.  It never reads results.
    """
    comps = _asc_components(components)
    k = len(comps)
    _max_order = _asc_int(max_order, where='max_order', minimum=1,
                          maximum=ASC_MAX_ORDER)
    if _max_order > k:
        raise ValueError(
            f'max_order={_max_order} exceeds the number of components {k}')
    _n_seeds = _asc_int(n_seeds, where='n_seeds', minimum=1)
    alpha = _validated_alpha(alpha, context='fractional_factorial_design alpha')  # noqa: F821
    relations = _asc_relations(comps, defining_relations)
    p = len(relations)
    span = _asc_span(relations, comps)
    resolution = (min(_asc_popcount(word) for word in span if word)
                  if p else k + 1)
    # A regular fraction is the set of subset masks orthogonal to every
    # defining relation: an even number of members of each relation is active.
    full = 1 << k
    relation_masks = [_asc_mask(rel, comps) for rel in relations]
    rows = [mask for mask in range(full)
            if all(_asc_popcount(mask & relation) % 2
                   == _asc_popcount(relation) % 2
                   for relation in relation_masks)]
    rows.sort(key=lambda mask: (_asc_popcount(mask), mask))
    expected = 1 << (k - p)
    if len(rows) != expected:  # pragma: no cover - algebra invariant
        raise RuntimeError(
            f'fraction has {len(rows)} cells, expected {expected}')
    targets = [mask for mask in _asc_all_words(k)
               if _asc_popcount(mask) <= _max_order]

    def _coset(mask):
        return min(mask ^ word for word in span)

    classes = {}
    for mask in targets:
        classes.setdefault(_coset(mask), []).append(mask)
    for key in list(classes):
        classes[key].sort(key=lambda mask: (_asc_popcount(mask), mask))
    # Every word in the coset, including orders above max_order, is confounded
    # with the target term in a regular fraction.  Report it so a "clear at
    # order <= 2" result is not mistaken for "clear of every higher order".
    higher = {}
    for key in classes:
        higher[key] = [key ^ word for word in span
                       if _asc_popcount(key ^ word) > _max_order]

    alias_classes = []
    for key in sorted(classes, key=lambda value: (
            min(_asc_popcount(m) for m in classes[value]), value)):
        members = classes[key]
        alias_classes.append({
            'representative': _asc_term_name(key, comps),
            'members': [_asc_term_name(m, comps) for m in members],
            'higher_order_members': [
                _asc_term_name(m, comps) for m in
                sorted(higher[key], key=lambda m: (_asc_popcount(m), m))],
            'has_main_effect': any(_asc_popcount(m) == 1 for m in members),
            'separated_at_declared_order': len(members) == 1,
            'separated_at_all_orders': (len(members) == 1
                                        and not higher[key]),
        })

    mains = [mask for mask in targets if _asc_popcount(mask) == 1]
    main_classes = {_coset(mask) for mask in mains}
    main_effects_separable = len(main_classes) == len(mains)
    main_effects_clear = all(len(classes[_coset(mask)]) == 1 for mask in mains)
    # Model selection: every main effect, then one representative per alias
    # class whose class contains no main effect.  Two terms from the same
    # coset are the same column and must never be entered together.
    selected = list(mains)
    selected_classes = set(main_classes)
    omitted = []
    # A regular fraction with distinct cosets gives orthogonal columns; one
    # term per coset can be added until the row count is exhausted (the
    # intercept consumes one column).  This keeps the default model
    # estimable even for a 2^(6-2) design, where 6 mains plus all 15 2FIs
    # cannot fit into 16 rows.
    capacity = len(rows)
    for order in range(2, _max_order + 1):
        for mask in targets:
            if _asc_popcount(mask) != order:
                continue
            key = _coset(mask)
            if key in selected_classes:
                continue
            if any(_asc_popcount(member) == 1 for member in classes[key]):
                omitted.append(mask)
                continue
            if len(selected) + 1 >= capacity:
                omitted.append(mask)
                continue
            selected.append(mask)
            selected_classes.add(key)
    selected.sort(key=lambda mask: (_asc_popcount(mask), mask))
    terms = {}
    for mask in targets:
        key = _coset(mask)
        others = [m for m in classes[key] if m != mask]
        terms[_asc_term_name(mask, comps)] = {
            'name': _asc_term_name(mask, comps),
            'order': _asc_popcount(mask),
            'aliased_with': [_asc_term_name(m, comps) for m in others],
            'aliased_higher_order': [
                _asc_term_name(m, comps) for m in
                sorted(higher[key], key=lambda m: (_asc_popcount(m), m))],
            'clear_at_declared_order': len(others) == 0,
            'separately_estimable': len(others) == 0,
            'model_column': mask in selected,
            'effect_scale': 1 << _asc_popcount(mask),
        }

    status = 'ok'
    problems = []
    warnings = []
    if not main_effects_separable:
        status = 'not_estimable'
        problems.append(
            'two or more main effects share an alias class; the design '
            'cannot separate them even under an effect-sparsity assumption')
    elif len(rows) < k + 1:
        status = 'not_estimable'
        problems.append(
            f'{len(rows)} fraction cells cannot fit an intercept plus '
            f'{k} main effects; the design matrix is rank deficient')
    elif resolution < 3:
        status = 'not_estimable'
        problems.append(
            f'resolution {resolution} leaves main effects unidentifiable')
    elif ((p != 0 and resolution < 5)
          or any(not row['clear_at_declared_order']
                 for row in terms.values())):
        status = 'warnings'
        if resolution < 4:
            warnings.append(
                'resolution III: each main effect is aliased with at least '
                'one two-factor interaction; main-effect screening requires '
                'the declared assumption that those interactions are '
                'negligible')
        else:
            warnings.append(
                'some two-factor interactions share an alias class; do not '
                'report them as separate effects')
    interaction_targets = [mask for mask in targets
                           if _asc_popcount(mask) >= 2]
    interactions_clear = bool(interaction_targets) and all(
        len(classes[_coset(mask)]) == 1 for mask in interaction_targets)
    # Planning counterpart: with m model terms, the Holm-corrected exact
    # sign-flip floor needs 2**n >= 2*m/alpha.  This is a conservative floor
    # (max-T can reach alpha with fewer seeds); report it explicitly so a
    # 5-seed budget is not mistaken for a design that can clear the family.
    try:
        min_n_holm = signflip_min_n_for_holm(  # noqa: F821 (part_10)
            len(selected), alpha=alpha, n_max=64)
    except Exception:
        min_n_holm = None
    seed_budget_sufficient = bool(
        min_n_holm is not None and _n_seeds >= min_n_holm)
    if min_n_holm is None:
        warnings.append(
            f'no seed count up to 64 can reach alpha={alpha} with a Holm '
            f'family of m={len(selected)} model terms; a Holm-only report is '
            'not resolvable at this design')
    elif not seed_budget_sufficient:
        warnings.append(
            f'n_seeds={_n_seeds} is below the Holm family floor '
            f'n={min_n_holm} for m={len(selected)} model terms; an exact '
            'Holm-corrected family cannot reach alpha at this budget (max-T '
            'may still be more powerful)')
    if status == 'ok' and not seed_budget_sufficient:
        status = 'warnings'
    # A design that cannot fit an intercept plus every main effect (or whose
    # main effects share an alias class) licenses nothing, even when the
    # alias algebra alone would look separable.  Keep the claim flags derived
    # from the same condition as the top-level flags so an artifact cannot
    # simultaneously say ``status='not_estimable'`` and
    # ``claim.main_effects_licensed=True``.
    main_effects_licensed = bool(
        main_effects_separable and len(rows) >= k + 1
        and status != 'not_estimable')
    interactions_licensed = bool(
        interactions_clear and status != 'not_estimable')
    n_full = 1 << k
    n_cells = len(rows)
    out = {
        'kind': ASC_KIND,
        'schema': ASC_SCHEMA,
        'status': status,
        'policy': dict(ASC_POLICY),
        'components': comps,
        'n_components': k,
        'max_order': _max_order,
        'defining_relations': relations,
        'resolution': resolution,
        'resolution_label': ('full' if p == 0 else _asc_roman(resolution)),
        'n_relations': p,
        'design': {
            'kind': 'regular_fractional_factorial',
            'coding': 'two-level ±1; row = active subset',
            'rows': n_cells,
            'expected_rows': expected,
            'full_lattice_rows': n_full,
            'defining_relations': relations,
            'span': [_asc_cell_label(mask, comps) for mask in span],
            'model_capacity_columns': capacity,
            'model_omitted_terms': [_asc_term_name(mask, comps)
                                    for mask in omitted],
            'alpha': float(alpha),
            'model_terms_tested': len(selected),
            'min_seeds_for_family_significance_holm': min_n_holm,
            'seed_budget_sufficient_holm': seed_budget_sufficient,
        },
        'n_cells': n_cells,
        'n_cells_full': n_full,
        'saved_cells': n_full - n_cells,
        'saved_fraction': (float(n_full - n_cells) / float(n_full)
                           if n_full else 0.0),
        'cells': [[comps[i] for i in range(k) if mask & (1 << i)]
                  for mask in rows],
        'missing_cells': [],
        'extra_cells': [],
        'n_seeds': _n_seeds,
        'seeds': [],
        'missing_seeds': {},
        'model_terms': [_asc_term_name(mask, comps) for mask in selected],
        'terms': terms,
        'alias_classes': alias_classes,
        'family': {},
        'main_effects_separable': bool(main_effects_separable),
        'main_effects_clear': bool(main_effects_clear),
        'main_effects_licensed': main_effects_licensed,
        'interactions_licensed': interactions_licensed,
        'requires_sparsity_assumption': bool(resolution < 4),
        'n_significant': 0,
        'n_significant_main': 0,
        'claim': {
            'main_effects_licensed': main_effects_licensed,
            'interactions_licensed': interactions_licensed,
            'screening_only': True,
            'requires_sparsity_assumption': bool(resolution < 4),
            'higher_order_aliases_assumed_negligible': True,
            'statement': (
                'a regular fractional-factorial screening readout; aliased '
                'terms are one estimable group, not separate effects, and '
                'any higher-order alias is assumed negligible'),
        },
        'problems': problems,
        'warnings': warnings,
        'note': (
            'main-effect screening on a regular fraction; it is not a '
            'complete lattice and cannot identify Shapley values or all '
            'pairwise interactions'),
    }
    return out


def _asc_normalise_cells(cells, components):
    if not isinstance(cells, dict):
        raise ValueError(
            f'cells must be a mapping subset -> per-seed PPL, got '
            f'{type(cells).__name__}')
    comps = list(components)
    index = {name: i for i, name in enumerate(comps)}
    out = {}
    for key, per_seed in cells.items():
        if isinstance(key, str):
            parts = [p.strip() for p in key.split('+') if p.strip()]
        elif isinstance(key, (list, tuple, set, frozenset)):
            parts = list(key)
        else:
            raise ValueError(
                f'cells: subset keys must be lists or "+"-joined strings, got '
                f'{type(key).__name__}')
        names = []
        for i, item in enumerate(parts):
            if not isinstance(item, str) or not item.strip():
                raise ValueError(
                    f'cells[{_asc_repr(key)}][{i}]: component names must be '
                    'non-empty strings')
            name = item.strip()
            if name not in index:
                raise ValueError(
                    f'cells[{_asc_repr(key)}]: unknown component {name!r}; '
                    f'declared components are {comps}')
            if name in names:
                raise ValueError(
                    f'cells[{_asc_repr(key)}]: subset repeats {name!r}')
            names.append(name)
        subset = frozenset(names)
        if subset in out:
            raise ValueError(
                f'cells: duplicate subset {sorted(subset)!r} after '
                'normalisation')
        if not isinstance(per_seed, dict):
            raise ValueError(
                f'cells[{_asc_repr(key)}]: per-seed values must be an object')
        vals = {}
        for seed_key, value in per_seed.items():
            seed = _as_seed_int(seed_key)  # noqa: F821 (part_13)
            if seed is None:
                raise ValueError(
                    f'cells[{_asc_repr(key)}]: seed {_asc_repr(seed_key)} is '
                    'not an integer')
            if seed in vals:
                raise ValueError(
                    f'cells[{_asc_repr(key)}]: duplicate seed {seed!r} after '
                    'normalisation')
            vals[seed] = _asc_finite(
                value, where=(
                    f'cells[{_asc_repr(key)}][seed={seed}]'), positive=True)
        out[subset] = vals
    return out


def _asc_cells_to_records(cells, components):
    order = {name: i for i, name in enumerate(components)}

    def _sort_key(subset):
        return (len(subset), tuple(sorted(order[name] for name in subset)))

    records = []
    for subset in sorted(cells, key=_sort_key):
        per = cells[subset]
        records.append({
            'subset': sorted(subset, key=lambda name: order[name]),
            'per_seed': {str(seed): per[seed] for seed in sorted(per)},
        })
    return records


def _asc_cells_from_records(records, components):
    if not isinstance(records, (list, tuple)):
        raise ValueError('inputs.cells must be a list of records')
    if len(records) > (1 << len(components)):
        raise ValueError(
            f'inputs.cells has {len(records)} records for a '
            f'{len(components)}-component screening design '
            f'(at most {1 << len(components)})')
    out = {}
    for i, rec in enumerate(records):
        if not isinstance(rec, dict):
            raise ValueError(f'inputs.cells[{i}] must be an object')
        subset = rec.get('subset')
        if not isinstance(subset, (list, tuple)):
            raise ValueError(f'inputs.cells[{i}].subset must be a list')
        per_seed = rec.get('per_seed')
        if not isinstance(per_seed, dict):
            raise ValueError(f'inputs.cells[{i}].per_seed must be an object')
        names = []
        for j, item in enumerate(subset):
            if not isinstance(item, str) or not item.strip():
                raise ValueError(
                    f'inputs.cells[{i}].subset[{j}] must be a non-empty string')
            name = item.strip()
            if name not in components:
                raise ValueError(
                    f'inputs.cells[{i}].subset[{j}]: unknown component '
                    f'{name!r}')
            if name in names:
                raise ValueError(
                    f'inputs.cells[{i}].subset repeats {name!r}')
            names.append(name)
        key = frozenset(names)
        if key in out:
            raise ValueError(
                f'inputs.cells: duplicate subset {sorted(key)!r}')
        vals = {}
        for seed_key, value in per_seed.items():
            seed = _as_seed_int(seed_key)  # noqa: F821 (part_13)
            if seed is None:
                raise ValueError(
                    f'inputs.cells[{i}]: seed {_asc_repr(seed_key)} is not an '
                    'integer')
            if seed in vals:
                raise ValueError(
                    f'inputs.cells[{i}]: duplicate seed {seed!r}')
            vals[seed] = _asc_finite(
                value, where=f'inputs.cells[{i}][seed={seed}]', positive=True)
        out[key] = vals
    return out


def _asc_term_mask(name, components):
    parts = [p.strip() for p in str(name).split('+') if p.strip()]
    if not parts:
        raise ValueError('term names must be non-empty')
    index = {component: i for i, component in enumerate(components)}
    mask = 0
    seen = set()
    for part in parts:
        if part not in index:
            raise ValueError(
                f'term {name!r} names unknown component {part!r}')
        if part in seen:
            raise ValueError(f'term {name!r} repeats component {part!r}')
        seen.add(part)
        mask |= 1 << index[part]
    return mask


def _asc_effect_stats(effects, *, alpha, min_n, seeds):
    stats = paired_effect_stats(  # noqa: F821 (part_10)
        effects, alpha=alpha, min_n=min_n, seeds=seeds)
    def _num(value):
        if isinstance(value, (bool, np.bool_)) or value is None:
            return None
        try:
            out = float(value)
        except (TypeError, ValueError, OverflowError):
            return None
        return out if _asc_math.isfinite(out) else None
    ci = None
    low, high = _num(stats.get('ci95_low')), _num(stats.get('ci95_high'))
    if low is not None and high is not None and low <= high:
        ci = [low, high]
    return {
        'n': int(stats.get('n') or 0),
        'mean': _num(stats.get('mean')),
        'std': _num(stats.get('std')),
        'sem': _num(stats.get('sem')),
        'ci95': ci,
        'p_exact_signflip': _num(stats.get('p_exact_signflip')),
        'p_floor': _num(stats.get('p_floor')),
        'significant': bool(stats.get('significant')),
        'within_seed_noise': bool(stats.get('within_seed_noise')),
        'seed_driven': (None if stats.get('seed_driven') is None
                        else bool(stats.get('seed_driven'))),
        'resolution_limited': bool(stats.get('resolution_limited')),
        '_raw': stats,
    }


def _asc_mark_not_estimable(result, reason):
    """Keep every schema field present when the design cannot be fitted."""
    result['status'] = 'not_estimable'
    result['problems'].append(reason)
    result['n_significant'] = 0
    result['n_significant_main'] = 0
    result['main_effects_licensed'] = False
    result['interactions_licensed'] = False
    claim = dict(result.get('claim') or {})
    claim.update({'main_effects_licensed': False,
                  'interactions_licensed': False,
                  'screening_only': True})
    result['claim'] = claim
    return result


def ablation_screening_analysis(cells, *, components=None,
                                defining_relations=None, max_order=2,
                                alpha=0.05, min_n=3, model_terms=None):
    """Fit and test the declared fractional-factorial screening design.

    The input is ``cells: subset -> {seed: positive PPL}``.  The subset keys
    must be exactly the 2^(k-p) cells generated by ``defining_relations``; a
    missing or extra cell makes the analysis ``not_estimable`` rather than
    silently fitting a different design.  Effects are per-seed OLS
    coefficients on the ±1 design matrix, scaled to log-PPL contrasts, and
    tested with the repository's exact sign-flip and max-T/Holm machinery.
    """
    alpha = _validated_alpha(alpha, context='ablation_screening alpha')  # noqa: F821
    _max_order = _asc_int(max_order, where='max_order', minimum=1,
                          maximum=ASC_MAX_ORDER)
    _min_n = _asc_int(min_n, where='min_n', minimum=2)
    if components is None:
        inferred = set()
        for key in (cells.keys() if isinstance(cells, dict) else []):
            if isinstance(key, str):
                inferred.update(p.strip() for p in key.split('+') if p.strip())
            elif isinstance(key, (list, tuple, set, frozenset)):
                inferred.update(str(p).strip() for p in key)
        if not inferred:
            raise ValueError('components cannot be inferred from empty cells')
        components = sorted(inferred)
    comps = _asc_components(components)
    k = len(comps)
    if _max_order > k:
        raise ValueError(
            f'max_order={_max_order} exceeds the number of components {k}')
    norm = _asc_normalise_cells(cells, comps)
    # Every cell may be present but carry an empty per-seed map (for example a
    # pending run).  The design's planning seed count is only used for its
    # resolution warning, so floor it at one and let the complete-case
    # intersection below report the real n=0 as not_estimable.  Passing 0 to
    # ``fractional_factorial_design`` would raise before that verdict is built.
    design = fractional_factorial_design(
        comps, defining_relations=defining_relations, max_order=_max_order,
        n_seeds=max(1, max((len(v) for v in norm.values()), default=0)),
        alpha=alpha)
    expected = {frozenset(row) for row in design['cells']}
    measured = set(norm)
    missing = sorted(expected - measured, key=lambda s: (len(s), sorted(s)))
    extra = sorted(measured - expected, key=lambda s: (len(s), sorted(s)))
    result = dict(design)
    result['n_seeds'] = 0
    result['seeds'] = []
    result['missing_cells'] = [sorted(subset) for subset in missing]
    result['extra_cells'] = [sorted(subset) for subset in extra]
    if missing or extra:
        reasons = []
        if missing:
            reasons.append(
                'measured cells do not cover the declared fraction; missing '
                + ', '.join(_asc_cell_label(_asc_mask(s, comps), comps)
                            for s in missing))
        if extra:
            reasons.append(
                'measured cells contain subsets outside the declared fraction: '
                + ', '.join(_asc_cell_label(_asc_mask(s, comps), comps)
                            for s in extra))
        return _asc_mark_not_estimable(result, '; '.join(reasons))

    # Common seed intersection: never average across different seed subsets.
    seed_sets = [set(per) for per in norm.values()]
    common = sorted(set.intersection(*seed_sets)) if seed_sets else []
    missing_seeds = {}
    for subset, per in norm.items():
        miss = sorted(set(per) - set(common))
        if miss:
            missing_seeds[_asc_cell_label(_asc_mask(subset, comps), comps)] = miss
    result['seeds'] = common
    result['n_seeds'] = len(common)
    result['missing_seeds'] = missing_seeds
    if design['status'] == 'not_estimable':
        # The design itself (rank deficiency, aliased main effects, or a
        # fraction smaller than the intercept-plus-mains model) cannot be
        # fitted.  Report that as the named not_estimable result instead of
        # falling through to the model-term check, which would raise on the
        # design's own aliased default model terms.
        reason = '; '.join(str(x) for x in (design.get('problems') or []))
        return _asc_mark_not_estimable(
            result,
            'declared screening design is not estimable'
            + (f': {reason}' if reason else ''))
    if len(common) < _min_n:
        return _asc_mark_not_estimable(
            result,
            f'complete-case seed intersection has n={len(common)} < '
            f'min_n={_min_n}; no screening effect is estimable')

    # Model terms: every main effect plus one representative per alias class.
    if model_terms is None:
        selected_names = list(design['model_terms'])
    else:
        if isinstance(model_terms, (str, bytes, bytearray)):
            raise ValueError('model_terms must be a list of term names')
        try:
            raw_terms = list(model_terms)
        except TypeError:
            raise ValueError('model_terms must be a list of term names'
                             ) from None
        selected_names = []
        for name in raw_terms:
            if not isinstance(name, str) or not name.strip():
                raise ValueError(
                    f'model_terms: names must be non-empty strings, got '
                    f'{_asc_repr(name)}')
            mask = _asc_term_mask(name.strip(), comps)
            if _asc_popcount(mask) > _max_order:
                raise ValueError(
                    f'model_terms: {name!r} is above max_order={_max_order}')
            selected_names.append(_asc_term_name(mask, comps))
        if len(set(selected_names)) != len(selected_names):
            raise ValueError('model_terms contains a duplicate term')
        mains = [_asc_term_name(mask, comps)
                 for mask in _asc_all_words(k) if _asc_popcount(mask) == 1]
        missing_mains = [name for name in mains if name not in selected_names]
        if missing_mains:
            raise ValueError(
                'model_terms must include every main effect; missing '
                + ', '.join(missing_mains))
        selected_names.sort(key=lambda name: (
            _asc_popcount(_asc_term_mask(name, comps)),
            _asc_term_mask(name, comps)))
    # Alias collisions among explicitly selected terms would make the design
    # matrix singular; detect them before fitting.
    masks = [_asc_term_mask(name, comps) for name in selected_names]
    span = _asc_span(design['defining_relations'], comps)
    def _coset(mask):
        return min(mask ^ word for word in span)
    cosets = {}
    for name, mask in zip(selected_names, masks):
        key = _coset(mask)
        if key in cosets:
            raise ValueError(
                f'model_terms selects aliased terms {cosets[key]!r} and '
                f'{name!r}; they are one estimable group, not two effects')
        cosets[key] = name
    result['model_terms'] = selected_names

    rows = [_asc_mask(row, comps) for row in design['cells']]
    X = []
    for cell in rows:
        row_values = [1.0]
        for term in masks:
            inactive = term ^ (cell & term)
            row_values.append(-1.0 if _asc_popcount(inactive) % 2 else 1.0)
        X.append(row_values)
    X = np.asarray(X, dtype=float)  # noqa: F821 (part_00 imports numpy)
    rank = int(np.linalg.matrix_rank(X))
    result['design']['design_matrix_rank'] = rank
    result['design']['design_matrix_columns'] = int(X.shape[1])
    if rank != X.shape[1]:
        return _asc_mark_not_estimable(
            result,
            f'design matrix rank {rank} < {X.shape[1]} columns; the selected '
            'terms are not jointly estimable')

    effects = {name: [] for name in selected_names}
    for seed in common:
        y = np.asarray([_asc_math.log(norm[frozenset(row)][seed])
                        for row in design['cells']], dtype=float)
        try:
            coef = np.linalg.lstsq(X, y, rcond=None)[0]
        except Exception as exc:  # pragma: no cover - numpy failure path
            return _asc_mark_not_estimable(
                result, f'per-seed OLS failed: {type(exc).__name__}: {exc}')
        if not np.all(np.isfinite(coef)):
            return _asc_mark_not_estimable(
                result, 'per-seed OLS produced a non-finite coefficient')
        for j, name in enumerate(selected_names):
            order = _asc_popcount(masks[j])
            effects[name].append(float((1 << order) * coef[j + 1]))

    term_rows = {}
    for j, name in enumerate(selected_names):
        stats = _asc_effect_stats(effects[name], alpha=alpha, min_n=_min_n,
                                  seeds=common)
        base = design['terms'][name]
        row = {
            'name': name,
            'order': _asc_popcount(masks[j]),
            'aliased_with': list(base['aliased_with']),
            'aliased_higher_order': list(base['aliased_higher_order']),
            'clear_at_declared_order': bool(base['clear_at_declared_order']),
            'separately_estimable': bool(base['separately_estimable']),
            'model_column': True,
            'effect_scale': int(1 << _asc_popcount(masks[j])),
            'ci95_simultaneous': None,
        }
        for key in ('n', 'mean', 'std', 'sem', 'ci95', 'p_exact_signflip',
                    'p_floor', 'significant', 'within_seed_noise',
                    'seed_driven', 'resolution_limited'):
            row[key] = stats[key]
        term_rows[name] = row

    named = {name: effects[name] for name in selected_names}
    fallback_reason = None
    family_method = 'exact_maxt'
    try:
        joint = maxt_signflip_adjust(named, alpha=alpha)  # noqa: F821 (part_40)
        family_p = {name: joint['contrasts'][name]['p_maxt']
                    for name in selected_names}
        p_floor_single = joint.get('p_floor_single')
        n_patterns = joint.get('n_patterns')
        simultaneous = {name: joint['contrasts'][name].get('ci_simultaneous')
                        for name in selected_names}
    except Exception as exc:
        family_method = 'holm_fallback'
        fallback_reason = f'{type(exc).__name__}: {exc}'
        family_pairs = [(name, term_rows[name]['p_exact_signflip'])
                        for name in selected_names]
        holm = holm_adjust(  # noqa: F821 (part_09)
            [(name, 1.0 if p is None else p) for name, p in family_pairs],
            alpha=alpha)
        family_p = {name: holm[name]['p_holm'] for name in selected_names}
        p_floor_single = min(
            (term_rows[name]['p_floor'] for name in selected_names
             if term_rows[name]['p_floor'] is not None), default=None)
        n_patterns = None
        simultaneous = {name: None for name in selected_names}
    for name in selected_names:
        p_family = family_p[name]
        term_rows[name]['p_family'] = (
            float(p_family) if p_family is not None
            and _asc_math.isfinite(float(p_family)) else None)
        term_rows[name]['family_method'] = family_method
        term_rows[name]['reject_family'] = bool(
            term_rows[name]['p_family'] is not None
            and term_rows[name]['p_family'] <= alpha
            and term_rows[name]['n'] >= _min_n
            and not term_rows[name]['within_seed_noise'])
        if simultaneous.get(name) is not None:
            term_rows[name]['ci95_simultaneous'] = simultaneous[name]
    n_significant = sum(1 for name in selected_names
                        if term_rows[name]['reject_family'])
    main_names = [name for name in selected_names
                  if _asc_popcount(_asc_term_mask(name, comps)) == 1]
    n_significant_main = sum(1 for name in main_names
                             if term_rows[name]['reject_family'])
    result['terms'] = term_rows
    result['family'] = {
        'method': family_method,
        'alpha': float(alpha),
        'm': len(selected_names),
        'p_floor_single': (float(p_floor_single)
                           if p_floor_single is not None else None),
        'p_floor_family_holm': (float(min(1.0, len(selected_names) *
                                         p_floor_single))
                                if p_floor_single is not None else None),
        'resolution_limited': bool(
            p_floor_single is not None and p_floor_single > alpha),
        'fallback_reason': fallback_reason,
        'n_patterns': n_patterns,
        'min_seeds_for_family_significance_holm': (
            design['design'].get('min_seeds_for_family_significance_holm')),
        'seed_budget_sufficient_holm': bool(
            design['design'].get('min_seeds_for_family_significance_holm')
            is not None
            and len(common) >= design['design'].get(
                'min_seeds_for_family_significance_holm')),
    }
    result['n_significant'] = int(n_significant)
    result['n_significant_main'] = int(n_significant_main)
    result['main_effects_separable'] = bool(
        design['main_effects_separable'])
    result['main_effects_clear'] = bool(all(
        not term_rows[name]['aliased_with'] for name in main_names))
    result['main_effects_licensed'] = bool(
        result['main_effects_separable'] and result['status'] != 'not_estimable')
    selected_interactions = [
        name for name in selected_names
        if _asc_popcount(_asc_term_mask(name, comps)) >= 2]
    result['interactions_licensed'] = bool(
        design['interactions_licensed'] and selected_interactions
        and all(term_rows[name]['separately_estimable']
                for name in selected_interactions))
    result['requires_sparsity_assumption'] = bool(
        design['resolution'] < 4)
    result['claim'] = {
        'main_effects_licensed': result['main_effects_licensed'],
        'interactions_licensed': result['interactions_licensed'],
        'screening_only': True,
        'requires_sparsity_assumption': result['requires_sparsity_assumption'],
        'higher_order_aliases_assumed_negligible': True,
        'statement': (
            'a regular fractional-factorial screening readout; aliased '
            'terms are one estimable group, not separate effects, and any '
            'higher-order alias is assumed negligible'),
    }
    if result['requires_sparsity_assumption']:
        msg = ('resolution III: main-effect estimates include aliased '
               'two-factor interactions; the screening claim depends on the '
               'sparsity-of-effects assumption')
        if msg not in result['warnings']:
            result['warnings'].append(msg)
    if result['status'] != 'not_estimable' and n_significant_main == 0:
        result['warnings'].append(
            'no main effect survives the family correction; this is a '
            'screening null, not evidence that every component is inert')
    if result['family']['resolution_limited']:
        result['warnings'].append(
            'the exact sign-flip family cannot reach alpha at this seed '
            'count; report a resolution limit, not a null result')
    if not result['family']['seed_budget_sufficient_holm']:
        result['warnings'].append(
            'the complete-case seed count is below the Holm family floor for '
            'this many model terms; any surviving term relies on the max-T '
            'reading, and a Holm-only report is resolution limited')
    if result['status'] != 'not_estimable':
        if n_significant_main == 0 or design['resolution'] < 4:
            result['status'] = 'warnings'
        else:
            result['status'] = 'ok'
    return result


def _asc_forbidden_paths(value, path='', out=None, limit=50):
    if out is None:
        out = []
    if len(out) >= limit:
        return out
    if isinstance(value, dict):
        for key, item in value.items():
            # The artifact is untrusted (possibly hand-written) JSON.  A huge
            # integer key can exceed CPython's integer->decimal limit while
            # this validator is constructing the diagnostic path, so fall back
            # to the bounded repr instead of aborting the report.
            try:
                name = str(key)
            except Exception:
                name = _asc_repr(key)
            if name in ASC_FORBIDDEN:
                out.append(f'{path}.{name}' if path else name)
                if len(out) >= limit:
                    break
            _asc_forbidden_paths(item, f'{path}.{name}' if path else name,
                                 out, limit)
    elif isinstance(value, (list, tuple)):
        for index, item in enumerate(value):
            _asc_forbidden_paths(item, f'{path}[{index}]', out, limit)
    return out


def _asc_json_equal(a, b):
    if isinstance(a, bool) or isinstance(b, bool):
        return a is b
    if isinstance(a, (int, float)) and isinstance(b, (int, float)):
        try:
            fa, fb = float(a), float(b)
        except (OverflowError, ValueError):
            return a == b
        if not (_asc_math.isfinite(fa) and _asc_math.isfinite(fb)):
            return a == b
        return abs(fa - fb) <= 1e-9 * max(1.0, abs(fa), abs(fb))
    if isinstance(a, dict) or isinstance(b, dict):
        if not (isinstance(a, dict) and isinstance(b, dict)):
            return False
        if set(a) != set(b):
            return False
        return all(_asc_json_equal(a[key], b[key]) for key in a)
    if isinstance(a, (list, tuple)) or isinstance(b, (list, tuple)):
        if not (isinstance(a, (list, tuple))
                and isinstance(b, (list, tuple))):
            return False
        return (len(a) == len(b)
                and all(_asc_json_equal(x, y) for x, y in zip(a, b)))
    return a == b


def _asc_diff_paths(stored, replay, path='result', out=None, limit=20):
    if out is None:
        out = []
    if len(out) >= limit:
        return out
    if isinstance(stored, dict) and isinstance(replay, dict):
        for key in sorted(set(stored) | set(replay), key=_asc_repr):
            if key not in stored:
                out.append(f'{path}.{key}: missing from stored artifact')
            elif key not in replay:
                out.append(f'{path}.{key}: not produced by replay')
            else:
                _asc_diff_paths(stored[key], replay[key],
                                f'{path}.{key}', out, limit)
            if len(out) >= limit:
                break
    elif (isinstance(stored, (list, tuple))
          and isinstance(replay, (list, tuple))):
        if len(stored) != len(replay):
            out.append(f'{path}: stored length {len(stored)} != replay '
                       f'length {len(replay)}')
        else:
            for index, (left, right) in enumerate(zip(stored, replay)):
                _asc_diff_paths(left, right, f'{path}[{index}]', out, limit)
                if len(out) >= limit:
                    break
    elif not _asc_json_equal(stored, replay):
        out.append(f'{path}: stored={_asc_repr(stored)}, '
                   f'replay={_asc_repr(replay)}')
    return out


def _asc_content_sha(artifact):
    body = {key: value for key, value in artifact.items()
            if key not in ('created_at', 'content_sha256')}
    return _sha256_json(body)  # noqa: F821 (part_00)


def build_ablation_screening(cells, *, components=None,
                             defining_relations=None, max_order=2,
                             alpha=0.05, min_n=3, model_terms=None,
                             created_at=None):
    """Run the screening analysis and stamp its canonical content hash."""
    result = ablation_screening_analysis(
        cells, components=components, defining_relations=defining_relations,
        max_order=max_order, alpha=alpha, min_n=min_n, model_terms=model_terms)
    comps = list(result['components'])
    norm = _asc_normalise_cells(cells, comps)
    inputs = {
        'components': comps,
        'defining_relations': result['defining_relations'],
        'max_order': int(result['max_order']),
        'alpha': float(alpha),
        'min_n': int(min_n),
        'model_terms': list(result['model_terms']),
        'cells': _asc_cells_to_records(norm, comps),
    }
    artifact = {
        'kind': ASC_ARTIFACT_KIND,
        'schema': ASC_SCHEMA,
        'created_at': created_at or _asc_time.strftime('%Y-%m-%dT%H:%M:%S'),
        'inputs': inputs,
        'result': result,
    }
    artifact['content_sha256'] = _asc_content_sha(artifact)
    return artifact


def validate_ablation_screening(artifact):
    """Replay a stored screening artifact from its declared inputs.

    Missing digest, a changed design/effect/p/alias field, a missing or extra
    cell, or a smuggled frozen-decision key is ``fail``.  A self-consistent
    but ``not_estimable``/``warnings`` result replays cleanly and keeps its
    own status.
    """
    out = {'kind': 'ablation_screening_validation', 'schema': 1,
           'status': 'fail', 'problems': [], 'warnings': [],
           'content_sha256': None, 'result': None, 'result_status': None}
    if not isinstance(artifact, dict):
        out['problems'].append('artifact must be a JSON object')
        return out
    if artifact.get('kind') != ASC_ARTIFACT_KIND:
        out['problems'].append(
            f'artifact.kind must be {ASC_ARTIFACT_KIND!r}, got '
            f'{_asc_repr(artifact.get("kind"))}')
    if artifact.get('schema') != ASC_SCHEMA:
        out['problems'].append(
            f'artifact.schema must be {ASC_SCHEMA}, got '
            f'{_asc_repr(artifact.get("schema"))}')
    stolen = _asc_forbidden_paths(artifact)
    if stolen:
        out['problems'].append(
            'artifact carries frozen-decision field(s): ' + ', '.join(stolen))
    extra_top = sorted((key for key in artifact if key not in ASC_TOP_KEYS),
                       key=_asc_repr)
    if extra_top:
        out['problems'].append(
            'artifact carries field(s) outside the replay schema: '
            + ', '.join(_asc_repr(key) for key in extra_top))
    inputs = artifact.get('inputs')
    if not isinstance(inputs, dict):
        out['problems'].append('artifact.inputs must be an object')
        inputs = {}
    missing = [key for key in ASC_INPUT_KEYS if key not in inputs]
    if missing:
        out['problems'].append(
            f'artifact.inputs is missing required key(s): {missing}')
    extra_inputs = sorted((key for key in inputs
                           if key not in ASC_INPUT_KEYS), key=_asc_repr)
    if extra_inputs:
        out['problems'].append(
            'artifact.inputs carries field(s) outside the schema: '
            + ', '.join(_asc_repr(key) for key in extra_inputs))
    recorded = artifact.get('content_sha256')
    out['content_sha256'] = recorded if isinstance(recorded, str) else None
    if not isinstance(recorded, str) or len(recorded) != 64:
        out['problems'].append(
            'artifact.content_sha256 must be a 64-hex string')
    else:
        try:
            replay_sha = _asc_content_sha(artifact)
        except Exception as exc:
            out['problems'].append(
                f'artifact cannot be hashed for replay: '
                f'{type(exc).__name__}: {exc}')
        else:
            if replay_sha != recorded:
                out['problems'].append(
                    'artifact.content_sha256 does not match the recorded body '
                    '(the artifact was edited after it was built)')
    if out['problems']:
        return out
    try:
        comps = _asc_components(inputs.get('components'))
        relations = _asc_relations(comps, inputs.get('defining_relations'))
        cells = _asc_cells_from_records(inputs.get('cells'), comps)
        replay = ablation_screening_analysis(
            cells, components=comps, defining_relations=relations,
            max_order=inputs.get('max_order'), alpha=inputs.get('alpha'),
            min_n=inputs.get('min_n'), model_terms=inputs.get('model_terms'))
    except Exception as exc:
        out['problems'].append(
            f'artifact inputs cannot be replayed: {type(exc).__name__}: {exc}')
        return out
    out['result'] = replay
    out['result_status'] = replay.get('status')
    stored = artifact.get('result')
    if not isinstance(stored, dict):
        out['problems'].append('artifact.result must be an object')
        return out
    extra = sorted((key for key in stored if key not in ASC_RESULT_KEYS),
                   key=_asc_repr)
    if extra:
        out['problems'].append(
            'artifact.result carries field(s) outside the schema: '
            + ', '.join(_asc_repr(key) for key in extra))
    missing_result = [key for key in ASC_RESULT_KEYS if key not in stored]
    if missing_result:
        out['problems'].append(
            f'artifact.result is missing field(s): {missing_result}')
    stored_terms = stored.get('terms')
    if isinstance(stored_terms, dict):
        for name, row in sorted(stored_terms.items(), key=lambda kv: _asc_repr(kv[0])):
            if not isinstance(row, dict):
                out['problems'].append(
                    f'artifact.result.terms[{_asc_repr(name)}] is not an object')
                continue
            extra = sorted(set(row) - set(ASC_TERM_KEYS), key=_asc_repr)
            if extra:
                out['problems'].append(
                    f'artifact.result.terms[{_asc_repr(name)}] carries '
                    'field(s) outside the schema: '
                    + ', '.join(_asc_repr(key) for key in extra))
    elif stored_terms is not None:
        out['problems'].append('artifact.result.terms must be an object')
    stored_family = stored.get('family')
    if isinstance(stored_family, dict) and stored_family:
        extra = sorted(set(stored_family) - set(ASC_FAMILY_KEYS), key=_asc_repr)
        if extra:
            out['problems'].append(
                'artifact.result.family carries field(s) outside the schema: '
                + ', '.join(_asc_repr(key) for key in extra))
    elif stored_family is not None and not isinstance(stored_family, dict):
        out['problems'].append('artifact.result.family must be an object')
    diffs = _asc_diff_paths(stored, replay)
    if diffs:
        out['problems'].append(
            'artifact.result does not replay from its declared inputs: '
            + '; '.join(diffs))
    if not out['problems']:
        out['status'] = 'ok'
    return out


def write_ablation_screening(outdir, artifact, *, overwrite=False):
    """Atomically persist ``ablation_screening.json``; never silently replace."""
    if isinstance(outdir, _asc_os.PathLike):
        outdir = _asc_os.fspath(outdir)
    if not isinstance(outdir, str) or not outdir.strip():
        raise ValueError('outdir must be a non-empty path')
    verdict = validate_ablation_screening(artifact)
    path = _asc_os.path.join(outdir, 'ablation_screening.json')
    out = {'kind': 'write_ablation_screening', 'path': path, 'written': False,
           'unchanged': False, 'conflict': False, 'status': verdict['status'],
           'artifact_status': (artifact.get('status')
                               if isinstance(artifact, dict) else None),
           'problems': list(verdict['problems'])}
    if verdict['status'] != 'ok':
        return out
    if _asc_os.path.exists(path):
        try:
            with open(path, encoding='utf-8') as handle:
                old = _asc_json.load(handle)
        except Exception:
            old = None
        if (isinstance(old, dict)
                and old.get('content_sha256') == artifact.get('content_sha256')):
            out['unchanged'] = True
            return out
        if not overwrite:
            out['conflict'] = True
            out['problems'].append(
                'a different ablation_screening.json already exists; pass '
                'overwrite=True only after re-running the analysis')
            return out
    _asc_os.makedirs(outdir, exist_ok=True)
    tmp = path + '.tmp'
    try:
        with open(tmp, 'w', encoding='utf-8') as handle:
            _asc_json.dump(artifact, handle, ensure_ascii=False, indent=1,
                           allow_nan=False)
            handle.write('\n')
    except Exception as exc:
        try:
            _asc_os.remove(tmp)
        except OSError:
            pass
        out['status'] = 'fail'
        out['problems'].append(
            f'artifact cannot be serialised: {type(exc).__name__}: {exc}')
        return out
    _asc_os.replace(tmp, path)
    out['written'] = True
    return out


def ablation_screening_markdown(result):
    """Render a compact term/alias table for a report appendix."""
    lines = ['| term | order | estimate (log PPL) | p (family) | aliased with |',
             '|---|---|---|---|---|']
    if isinstance(result, dict) and isinstance(result.get('terms'), dict):
        for name, row in sorted(result['terms'].items(),
                                key=lambda kv: (kv[1].get('order', 0), kv[0])):
            mean = row.get('mean')
            p = row.get('p_family')
            mean_text = f'{mean:.6g}' if mean is not None else 'n/a'
            p_text = f'{p:.4g}' if p is not None else 'n/a'
            alias = ', '.join(row.get('aliased_with') or []) or '--'
            lines.append(
                f'| {name} | {row.get("order")} | {mean_text} | {p_text} | '
                f'{alias} |')
    lines.append('')
    family = result.get('family') if isinstance(result, dict) else {}
    family = family if isinstance(family, dict) else {}
    lines.append(
        f"design: `{result.get('resolution_label') if isinstance(result, dict) else None}`; "
        f"cells={result.get('n_cells') if isinstance(result, dict) else None}; "
        f"family=`{family.get('method')}`; "
        f"main effects licensed="
        f"{result.get('main_effects_licensed') if isinstance(result, dict) else None}")
    return '\n'.join(lines)
